#!/usr/bin/env python3
"""Independent fixed-zero analyzer evidence and exact CN36 causal replay.

Only frozen v36 receiver and source access are imported. The new analyzer and
sender are not imported. Preparation evidence is independently regenerated by
the original frozen analyzer against each actual current canonical reference.
"""
from pathlib import Path
import hashlib,importlib.util,json,math,statistics,sys
import numpy as np

HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]
spec=importlib.util.spec_from_file_location('analysis37_independent_frozen36',HERE.parent/'python-game-canonical-v36-study/verify.py')
frozen=importlib.util.module_from_spec(spec);sys.modules[spec.name]=frozen;spec.loader.exec_module(frozen)
DIRECT=HERE.parent/'python-game-direct-v37-study'

def load(path):return json.loads(Path(path).read_text())
def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def raw(desc,folder=HERE):return frozen.frozen.raw(desc,folder)
def planes_sha(planes):return hashlib.sha256(b''.join(p.astype('<i2').tobytes() for p in planes)).hexdigest()

def ordered(rows):
    if (not isinstance(rows,list) or len(rows)!=48 or any(type(r.get('id'))is not int for r in rows)
            or [r['id'] for r in rows]!=list(range(48))):raise ValueError('exact ordered48 cohort')

def exact_wire(packet,expected):
    if type(packet)is not bytes or type(expected)is not bytes or packet!=expected:
        raise ValueError('all retained CN36 direct-sender bytes must match')
    return frozen.parse(packet)

def timings(row):
    values=row['paired_timing_ms']
    if (not isinstance(values,dict) or set(values)!={'direct','faster'} or
            any(not isinstance(v,list) or len(v)!=3 for v in values.values()) or
            any(type(x) not in (int,float) or not math.isfinite(x) or x<=0 for v in values.values() for x in v)):
        raise ValueError('three finite positive paired timing samples')
    medians={k:statistics.median(v) for k,v in values.items()}
    assert medians==row['paired_median_ms']
    orders=[list(('direct','faster') if (row['id']+rep)%2==0 else ('faster','direct')) for rep in range(3)]
    assert orders==row['paired_order']
    return medians

def preparation_evidence(p):
    return dict(prediction_sha256=planes_sha(p.prediction),raw_coefficients_sha256=planes_sha(p.raw_coefficients),source_sha256=planes_sha(p.source))

def check_work(row,prepared):
    aw,dw=row['analysis_work'],row['direct_work']
    assert aw['old_analyze_calls']==0 and aw['old_four_tap_prediction_calls']==0
    assert aw['zero_map_copy_prediction']is (not row['key'])
    assert aw['forward_plane_calls']==3 and aw['motion_mode']=='zero' and aw['block_size']==32
    assert aw['reference_tag']==prepared.reference_tag.hex()
    for k,v in (('prediction_array_bytes',prepared.prediction),('raw_coefficient_array_bytes',prepared.raw_coefficients),('source_array_bytes',prepared.source)):
        assert aw[k]==sum(p.nbytes for p in v)
    assert aw['retained_analysis_array_bytes']==sum(p.nbytes for p in prepared.prediction+prepared.raw_coefficients+prepared.source)
    for k,v in dict(full_packet_encode_calls=0,coefficient_parse_calls=0,skip_entropy_plane_constructions=3,
                    output_inverse_reconstructions=1,normalization_passes=1,wrappers=1).items():assert dw[k]==v
    assert dw['raw_forward_and_RDO_work_retained']is True and dw['compiled_mask_plan_setup_paid_once']is True
    assert math.isfinite(aw['analysis_wall_ms']) and aw['analysis_wall_ms']>0
    assert math.isfinite(dw['direct_encode_ms']) and dw['direct_encode_ms']>0
    assert aw['analysis_wall_ms']+dw['direct_encode_ms']<=row['paired_timing_ms']['faster'][-1]

def main():
    data=load(HERE/'results.json');assert data['schema']=='gamebub-analysis-v37'
    assert data['physical_30fps_proven']is False and data['new_RTL_implemented']is False
    for name,tag in data['source_sha256'].items():
        path=Path(name);assert not path.is_absolute() and '..' not in path.parts
        assert sha(ROOT/path)==tag,('producer pin',name)
    inputs=load(frozen.n.V24/'results.json')['inputs'];prior=load(DIRECT/'results.json')
    assert [c['scene'] for c in data['cases']]==['mass-effect-2600','mass-effect-7200']
    count=main_bytes=hud_words=0
    for case in data['cases']:
        old=next(c for c in prior['cases'] if c['scene']==case['scene'])
        sources=next(c for c in inputs if c['scene']==case['scene'])['rows']
        ordered(case['rows']);rx=frozen.Receiver();old_rx=frozen.Receiver();checks=[]
        for row,expected,source in zip(case['rows'],old['rows'],sources,strict=True):
            fid=row['id'];key=fid%24==0;rid=frozen.m.NO_REF if key else fid-1
            assert row['key']==key and row['reference_id']==rid
            assert row['source_sha256']==source['common_yuv420_u8_sha256']==expected['source_sha256']
            ref=None if key else rx.reference
            original_prepared=frozen.m.analyze_planes(frozen.n.source(source),ref,epoch=25,frame_id=fid,reference_id=rid,
                block_size=32,motion_mode='zero',penalty=0,motion_precision='half')
            assert preparation_evidence(original_prepared)==row['prepared_evidence']
            packet=raw(row['packet']);archived=raw(expected['packet'],DIRECT)
            meta=exact_wire(packet,archived)
            assert meta['skip'] and meta['key']==key and meta['frame_id']==fid and meta['reference_id']==rid
            assert meta['reference_tag']==original_prepared.reference_tag
            assert row['reference_tag']==original_prepared.reference_tag.hex()
            planes,patches,_=rx.receive(packet);old_planes,old_patches,_=old_rx.receive(archived)
            for a,b in zip(planes,old_planes,strict=True):np.testing.assert_array_equal(a,b)
            assert frozen.m.C.reference_tag(planes).hex()==row['normalized_tag']==expected['normalized_tag']
            assert len(packet)==row['complete_bytes']==expected['complete_bytes']<=49152
            assert raw(row['inner'])==meta['base']
            assert row['inner_bytes']==len(meta['base']) and row['hud_bytes']==len(meta['hud']) and row['binding_bytes']==80
            assert len(packet)==row['inner_bytes']+row['hud_bytes']+80
            original=frozen.n.original(source)
            expected_patches=tuple(original[y:y+h,x:x+w] for x,y,w,h in frozen.n.RECTS)
            for a,b,c in zip(patches,old_patches,expected_patches,strict=True):
                np.testing.assert_array_equal(a['words'],b['words']);np.testing.assert_array_equal(a['words'],c)
            quality,tag=frozen.metric(planes,original,patches)
            assert quality==row['hybrid']==expected['hybrid'] and tag==row['display_sha256']==expected['display_sha256']
            parsed=frozen.m.parse(meta['base'],expected_epoch=25)
            assert parsed['block_size']==32 and not np.any(parsed['vectors']) and row.get('background',16)==16
            np.testing.assert_array_equal(parsed['scale_map'],frozen.m.roi.declared_map(720,480,frozen.n.ROIS,8,16))
            for coeff,safe in zip(parsed['coefficients'],frozen.safe_blocks(),strict=True):assert not np.any(coeff[safe.reshape(-1)])
            medians=timings(row)
            check_work(row,original_prepared)
            checks.append(dict(bytes=len(packet),quality=quality,medians=medians));count+=1;main_bytes+=len(packet)
            hud_words+=sum(p['words'].size for p in patches)
        s=case['summary'];assert s['frames']==48 and s['complete_bytes']==sum(v['bytes'] for v in checks)
        assert s['maximum_complete_bytes']==max(v['bytes'] for v in checks)
        means={k:statistics.mean(v['medians'][k] for v in checks) for k in ('direct','faster')}
        for k,v in means.items():assert math.isclose(s['mean_paired_medians_ms'][k],v,abs_tol=1e-10)
        assert math.isclose(s['paired_sender_ratio'],means['direct']/means['faster'],abs_tol=1e-10)
        assert s['active_mse']==sum(v['quality']['active_squared_error'] for v in checks)/sum(v['quality']['active_channel_samples'] for v in checks)
    assert count==96 and hud_words==96*21120
    print(json.dumps(dict(exact_CN36_packets=count,exact_preparation_hashes=3*count,exact_complete_bytes=main_bytes,
                          exact_HUD_words=hud_words,source_pins=len(data['source_sha256']),whole_causal_reference_parity=True,
                          new_analyzer_or_encoder_imported=False,physical_30fps_proven=False)))

if __name__=='__main__':main()
