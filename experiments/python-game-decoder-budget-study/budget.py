"""Conditional AR02 decoder operation/capacity/burst-service model, not RTL."""
from dataclasses import asdict, dataclass
from math import ceil

@dataclass(frozen=True)
class Architecture:
    name: str = 'nominal'
    clock_hz: int = 100_000_000
    dsp_lanes: int = 8
    mac_ii: int = 1
    entropy_bits_per_cycle: int = 4
    samples_per_cycle: int = 2
    ui_words_per_cycle: int = 1
    sha_cycles_per_block: int = 80
    inverse_pipeline_cycles_per_block: int = 16
    read_burst_cycles: int = 15
    write_burst_cycles: int = 13
    burst_bytes: int = 16
    refresh_fraction: float = .03
    display_width: int = 800
    display_height: int = 480
    display_hz: int = 60

    def validate(self):
        numbers=asdict(self);numbers.pop('name');refresh=numbers.pop('refresh_fraction')
        if any(type(v) is not int or v<=0 for v in numbers.values()) or not 0<=refresh<1:
            raise ValueError('positive integer architecture fields and bounded refresh fraction')


def operations(trace):
    """Exact loop counts for Q14 separable transform; architecture-neutral counts."""
    full=sum(p['general_inverse'] for p in trace['planes'])
    dc=sum(p['dc_only'] for p in trace['planes']);zero=sum(p['zero'] for p in trace['planes'])
    pixels=trace['width']*trace['height'];yuv=pixels*3//2
    # inverse(a)=Q14.T @ ((a@Q14+8192)>>14): two 8x8x8 passes.
    return dict(general_blocks=full,dc_only_blocks=dc,zero_blocks=zero,
                inverse_multiply_accumulates=1024*full+2*dc,
                dequantization_multiplications=64*full+dc,
                yuv_clip_add_samples=yuv,chroma_upsample_output_pixels=pixels,
                rgb_matrix_multiplications=4*pixels,rgb565_output_pixels=pixels,
                selected_ui_words=trace['ui_pixels'],entropy_input_bits=8*trace['plane_payload_bytes'],
                canonical_tag_input_bytes=4+2*yuv if trace['publication'] else 0,
                packet_crc_bytes=trace.get('crc_validation_bytes',trace['packet_bytes']))


def traffic(trace):
    """Packed8-bit banks, external reconstruction, line-buffered color, local UI."""
    pixels=trace['width']*trace['height'];yuv=pixels*3//2
    return dict(compressed_staging_write=trace['packet_bytes'],compressed_staging_read=trace['packet_bytes'],
                prediction_reference_read=0 if trace['key'] else yuv,
                reconstructed_yuv_write=yuv,reconstructed_yuv_color_read=yuv,
                # Canonical int16 hash is generated by widening packed8-bit memory samples.
                publication_yuv_tag_read=yuv if trace['publication'] else 0,
                rgb565_display_write=2*pixels,
                extra_ui_external_read=0,extra_ui_external_write=0)


def capacity(width=720,height=480,frame_cap=49152,patch_pixels=21120,display_width=800,display_height=480):
    pixels=width*height;yuv=pixels*3//2
    return dict(packed8bit_two_reference_banks=2*yuv,
                three_panel_rgb565_buffers=3*2*display_width*display_height,
                two_compressed_ingress_slots=2*frame_cap,
                private_reconstruction_yuv=yuv,
                local_four_patch_decoded_words=2*patch_pixels,
                # Full-frame coefficients aren't necessary in a streaming design, but this
                # explicitly conservative candidate allocates them rather than hiding scratch.
                candidate_full_frame_int16_coefficients=2*yuv,
                color_two_chroma_row_buffers=2*(width//2)*2,
                metadata_reserved=4096)


def estimate(trace,arch=Architecture()):
    arch.validate();op=operations(trace);moves=traffic(trace)
    stages=dict(entropy=ceil(op['entropy_input_bits']/arch.entropy_bits_per_cycle),
                inverse_dequant=ceil((op['inverse_multiply_accumulates']+op['dequantization_multiplications'])/arch.dsp_lanes)*arch.mac_ii+
                  op['general_blocks']*arch.inverse_pipeline_cycles_per_block,
                reconstruction_clip=ceil(op['yuv_clip_add_samples']/arch.samples_per_cycle),
                chroma_upsample=ceil(op['chroma_upsample_output_pixels']/arch.samples_per_cycle),
                rgb_matrix=ceil(op['rgb_matrix_multiplications']/arch.dsp_lanes)*arch.mac_ii,
                rgb565_pack=ceil(op['rgb565_output_pixels']/arch.samples_per_cycle),
                ui_decode_mux=ceil(op['selected_ui_words']/arch.ui_words_per_cycle),
                sha_tag=ceil((op['canonical_tag_input_bytes']+9)/64)*arch.sha_cycles_per_block if trace['publication'] else 0,
                crc_validation=op['packet_crc_bytes'])
    compute=sum(stages.values());mem_cycles=0;burst_counts={}
    for name,n in moves.items():
        bursts=ceil(n/arch.burst_bytes);burst_counts[name]=bursts
        mem_cycles+=bursts*(arch.write_burst_cycles if name.endswith('write') else arch.read_burst_cycles)
    display_bytes_second=arch.display_width*arch.display_height*2*arch.display_hz
    # Round each scanline, not merely the aggregate, to expose partial burst tails.
    line_bursts=ceil(2*arch.display_width/arch.burst_bytes)
    scan_cycles_second=line_bursts*arch.display_height*arch.display_hz*arch.read_burst_cycles
    available=arch.clock_hz*(1-arch.refresh_fraction)-scan_cycles_second
    compute_ms=1000*compute/arch.clock_hz
    memory_ms=None if available<=0 else 1000*mem_cycles/available
    # Intentionally serialized per-frame stages + fair-residual average memory service.
    # This is a planning schedule assumption, NOT a worst-case deadline guarantee.
    planning_ms=None if memory_ms is None else compute_ms+memory_ms
    return dict(architecture=asdict(arch),operations=op,traffic_bytes=moves,
                burst_counts=burst_counts,stage_cycles=stages,compute_cycles=compute,
                compute_serialized_ms=compute_ms,background_memory_cycles=mem_cycles,
                scanout_bytes_per_second=display_bytes_second,scanout_cycles_per_second=scan_cycles_second,
                background_available_cycles_per_second=available,
                background_average_service_ms=memory_ms,serialized_planning_frame_ms=planning_ms,
                throughput_ceiling_roofline_fps=None if memory_ms is None else 1000/max(compute_ms,memory_ms),
                serialized_planning_fps=None if planning_ms is None else 1000/planning_ms,
                passes_average_30fps_budget=planning_ms is not None and planning_ms<=1000/30,
                required_average_bus_clock_hz_for_30fps=scan_cycles_second/(1-arch.refresh_fraction)+30*mem_cycles/(1-arch.refresh_fraction),
                line_deadline_proven=False,hardware_fit_proven=False)


def scenarios():
    return [Architecture(name='conservative',clock_hz=50_000_000,dsp_lanes=1,entropy_bits_per_cycle=1,samples_per_cycle=1,
                         read_burst_cycles=23,write_burst_cycles=21,refresh_fraction=.05),
            Architecture(),
            Architecture(name='optimistic',dsp_lanes=16,entropy_bits_per_cycle=8,samples_per_cycle=4,
                         read_burst_cycles=8,write_burst_cycles=8,refresh_fraction=.01)]
