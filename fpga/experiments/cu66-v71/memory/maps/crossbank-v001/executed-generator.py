#!/usr/bin/env python3
"""One checked word/byte-address map for RTL, native tests and future firmware."""
import hashlib,json
from pathlib import Path
H=Path('C:\\mb70\\fpga\\experiments\\cu66-v71\\memory\\maps\\crossbank-v001')
regions=[]
def add(name,base,size,kind,bank=None):
 assert base%16==size%16==0 and 0<=base<base+size<=32*1024*1024
 regions.append(dict(name=name,byte_base=base,byte_size=size,word_base=base//2,word_count=size//2,kind=kind,bank=bank))
for i,base in enumerate((0x100000,0x900000,0x1100000)):add(f'canonical{i}',base,518400,'canonical',i)
for i,base in enumerate((0x200000,0xa00000,0x1200000)):add(f'hud{i}',base,42240,'hud',i)
for i,base in enumerate((0x1800000,0x1300000)):add(f'rgb{i}',base,768000,'rgb',i)
for i,base in enumerate((0x1c00000,0x1c10000)):add(f'compressed{i}',base,49152,'compressed',i)
add('diagnostic',0x1ff0000,65536,'diagnostic')
for a in regions:
 for b in regions:
  if a is not b:assert a['byte_base']+a['byte_size']<=b['byte_base']-32 or b['byte_base']+b['byte_size']<=a['byte_base']-32
schema=dict(schema='cu71-memory-map-crossbank-v1',physical_bytes=32*1024*1024,physical_words=16*1024*1024,word_bytes=2,guard_bytes=32,regions=regions,plane_offsets_words=[0,172800,216000],plane_width_bytes=[720,360,360],plane_heights=[480,240,240],notes=['one mapped x16 SDRAM chip','region bases deliberately span all four internal SDRAM banks','guards and unallocated memory must be rejected by public aux API','controller BL8 may read only inside one allocated region; all region ends8wordaligned'])
(H/'memory-map.json').write_text(json.dumps(schema,indent=2)+'\n')
sv=['// Generated by generate_map.py. Addresses and sizes below are x16 words.']
cpp=['// Generated by generate_map.py. Addresses and sizes below are x16 words.','#pragma once','#include <cstdint>','namespace cu70_map {']
for r in regions:
 name=r['name'].upper();sv += [f"localparam logic [23:0] {name}_BASE=24'h{r['word_base']:06x};",f"localparam logic [24:0] {name}_WORDS=25'd{r['word_count']};"]
 cpp += [f"constexpr uint32_t {name}_BASE=0x{r['word_base']:06x};",f"constexpr uint32_t {name}_WORDS={r['word_count']};"]
sv+=['function automatic logic map_word_allowed(input logic [23:0] address);','begin','map_word_allowed=0;']
for r in regions:sv += [f"if(address>={r['name'].upper()}_BASE && {{1'b0,address}}<{{1'b0,{r['name'].upper()}_BASE}}+{r['name'].upper()}_WORDS)map_word_allowed=1;"]
sv+=['end','endfunction','function automatic logic [23:0] canonical_base(input logic [1:0] bank);','case(bank)','0:canonical_base=CANONICAL0_BASE;','1:canonical_base=CANONICAL1_BASE;','2:canonical_base=CANONICAL2_BASE;','default:canonical_base=0;','endcase','endfunction']
cpp+=['inline bool allowed(uint32_t address){']
for r in regions:cpp += [f"if(address>={r['name'].upper()}_BASE && address<{r['name'].upper()}_BASE+{r['name'].upper()}_WORDS)return true;"]
cpp+=['return false;}','inline uint32_t canonical_base(unsigned bank){return bank==0?CANONICAL0_BASE:bank==1?CANONICAL1_BASE:CANONICAL2_BASE;}','}']
(H/'cu70_memory_map.svh').write_text('\n'.join(sv)+'\n');(H/'memory_map.hpp').write_text('\n'.join(cpp)+'\n')
print('MAP_PASS regions='+str(len(regions))+' address_words=16777216 logical_allocated_bytes='+str(sum(r['byte_size']for r in regions)))
