def struct_error():
    import struct
    return struct.error

def check_json_lf(root: Path):
    files=sorted(root.rglob('*.json'))
    for p in files:
        raw=p.read_bytes()
        if b'\r' in raw or not raw.endswith(b'\n'):
            raise SystemExit(f'FAIL: noncanonical JSON line endings: {p.name}')
        json.loads(raw.decode('utf-8'))
    return len(files)

def verify(source: Path, out: Path, plan_repo: Path):
    check_source_inputs(source)
    with tempfile.TemporaryDirectory(prefix='ar03-contract-verify-') as td:
        build_tmp=Path(td)
        build(source,build_tmp,plan_repo)
        names=['wire-contract.json','development-profile.json','gb_wire.h','fg19-history.jsonl',
               'fg19-history-index.json','negative-wire-vectors.json','capability-matrix.json','plan-source.json',
               *['plan-source/'+Path(rel).name for rel in PLAN_FILES],'bundle-manifest.json']
        diffs=[n for n in names if not (out/n).is_file() or (out/n).read_bytes()!=(build_tmp/n).read_bytes()]
        if diffs: raise SystemExit('FAIL: bundle differs from deterministic rebuild: '+', '.join(diffs))
        json_count=check_json_lf(out)
        # Cross-check exact JSON and generated header against pinned existing outputs.
        kit=source/'hardware/gamebub-v20'
        assert (out/'wire-contract.json').read_bytes()==(kit/'wire-contract.json').read_bytes()
        assert (out/'development-profile.json').read_bytes()==(kit/'development-profile.json').read_bytes()
        assert (out/'gb_wire.h').read_bytes()==(kit/'include/gb_wire.h').read_bytes()
        rows=[json.loads(line) for line in (out/'fg19-history.jsonl').read_text().splitlines()]
        assert len(rows)==1725 and len({r['wire_sha256'] for r in rows})>1000
        return {'passed':True,'artifact_files':len(names),'history_records':len(rows),
                'negative_vectors':len(load_json(out/'negative-wire-vectors.json')['vectors']),
                'wire_json_verbatim':True,'development_json_verbatim':True,'header_matches_source_export':True,
                'canonical_json_lf':True,'json_files_checked':json_count}

def main():
    p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);p.add_argument('--out',type=Path,default=HERE)
    p.add_argument('--plan-repo',type=Path,default=PLAN_REPO_DEFAULT);p.add_argument('--verify-only',action='store_true');a=p.parse_args()
    source=a.source.resolve(); out=a.out.resolve(); plan_repo=a.plan_repo.resolve()
    if a.verify_only and not out.is_dir(): raise SystemExit('FAIL: --verify-only requires an existing bundle directory')
    if not a.verify_only: out.mkdir(parents=True,exist_ok=True);build(source,out,plan_repo)
    result=verify(source,out,plan_repo)
    print(json.dumps(result,sort_keys=True))
if __name__=='__main__':main()
