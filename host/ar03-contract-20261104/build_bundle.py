    add('unknown_kind_crc_valid',reseal(good[:5]+bytes([9])+good[6:32]),'reject')
    add('illegal_slot_2_crc_valid',reseal(good[:6]+(2).to_bytes(2,'big')+good[8:32]),'reject')
    add('zero_length_crc_valid',reseal(good[:24]+bytes(4)+good[28:32]),'reject')
