def sha(data: bytes) -> str: return hashlib.sha256(data).hexdigest()
def load_json(p: Path): return json.loads(p.read_text(encoding='utf-8'))
def write_json(p: Path, obj): p.write_text(json.dumps(obj, indent=2, sort_keys=True) + '\n', encoding='utf-8', newline='\n')

def git_blob(repo: Path, commit: str, rel: str) -> bytes:
    subprocess.check_call(['git','-C',str(repo),'cat-file','-e',commit+'^{commit}'],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    return subprocess.check_output(['git','-C',str(repo),'show',f'{commit}:{rel}'])

def require_bound_bytes(candidate: Path, expected: bytes, label: str):
    actual=candidate.read_bytes()
    if actual != expected: raise SystemExit(f'FAIL: source binding mismatch: {label}')

def check_source_inputs(source: Path):
    actual=subprocess.check_output(['git','-C',str(source),'rev-parse','HEAD'],text=True).strip()
    if actual != SOURCE_COMMIT: raise SystemExit(f'FAIL: source kit HEAD {actual} != pinned {SOURCE_COMMIT}')
    for rel in SOURCE_INPUTS:
        require_bound_bytes(source/rel,git_blob(source,SOURCE_COMMIT,rel),rel)

def source_parser(source: Path):
    p = source / 'experiments/python-game-frame-grant-study/frame_credit.py'
    spec = importlib.util.spec_from_file_location('pinned_frame_credit', p)
    mod = importlib.util.module_from_spec(spec); sys.modules[spec.name] = mod; spec.loader.exec_module(mod)
    return mod

def header(contract):
    lines = ['/* Generated by export_contract.py; byte offsets, never cast packed C structs. */',
             '#ifndef GB_V20_WIRE_H', '#define GB_V20_WIRE_H']
    for name, desc in contract['layouts'].items():
        lines.append(f'#define GB_V20_{name}_FIELD_BYTES {desc["field_bytes"]}u')
        for field in desc['fields']:
            lines.append(f'#define GB_V20_{name}_{field["name"].upper()}_OFFSET {field["offset"]}u')
    for name, value in contract['values']['frame_control'].items():
        lines.append(f'#define GB_V20_FG19_{name} {value}u')
    lines += [f'#define GB_V20_COMPLETE_CAP {contract["limits"]["complete_frame_cap"]}u',
              f'#define GB_V20_GF_PAYLOAD {contract["limits"]["gf_payload_bytes"]}u', '#endif']
    return '\n'.join(lines) + '\n'

def reseal(raw: bytes) -> bytes:
    return raw[:32] + zlib.crc32(raw[:32]).to_bytes(4, 'big')

def build(source: Path, out: Path, plan_repo: Path):
    check_source_inputs(source)
    kit = source / 'hardware/gamebub-v20'
    wire_src, profile_src = kit/'wire-contract.json', kit/'development-profile.json'
