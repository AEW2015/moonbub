    # Syntactically allowed NO_SLOT on REQUEST is rejected by current grammar.
    add('request_with_no_slot_crc_valid',reseal(good[:6]+(65535).to_bytes(2,'big')+good[8:32]),'reject')
    write_json(out/'negative-wire-vectors.json',{'schema':'offline-fg19-negative-vectors-v1',
        'basis':'pinned frame_credit.parse lab grammar; epoch fixed at 1; not a live negotiation protocol',
        'vectors':cases})
