    parser = source_parser(source)
    records=[]
    for case_index, case in enumerate(wire['frame_control_sequences']):
        for event_index, event in enumerate(case['events']):
            packet = bytes.fromhex(event['wire_hex'])
            parsed = parser.parse(packet)
            assert parsed == event['parsed'], (case_index,event_index,parsed,event['parsed'])
            records.append({'ordinal':len(records),'profile':case['profile'],'event':event['event'],
                'wire_hex':event['wire_hex'],'wire_sha256':sha(packet),'parsed':parsed,
                'original_model_at_ms':event['original_model_at_ms'],'delivered':event['delivered'],
                'provenance':'retained model-history serialization in pinned wire-contract.json'})
    assert len(records)==1725, len(records)
    jsonl=''.join(json.dumps(r,sort_keys=True,separators=(',',':'))+'\n' for r in records).encode()
    (out/'fg19-history.jsonl').write_bytes(jsonl)
    index={'schema':'offline-fg19-history-index-v1','record_count':len(records),
        'jsonl_sha256':sha(jsonl),'records':[{'ordinal':r['ordinal'],'profile':r['profile'],'event':r['event'],
            'wire_sha256':r['wire_sha256']} for r in records]}
    write_json(out/'fg19-history-index.json',index)

    # Negative vectors exercise only the existing lab epoch-1 parser grammar.
    good=bytes.fromhex(next(e['wire_hex'] for c in wire['frame_control_sequences'] for e in c['events']))
    cases=[]
    def add(name, packet, expected):
        try: parser.parse(packet)
        except (ValueError, struct_error()) as exc: actual='reject'; reason=str(exc)
        else: actual='accept'; reason=None
        assert actual==expected, (name, actual, reason)
        cases.append({'name':name,'wire_hex':packet.hex(),'wire_sha256':sha(packet),
                      'expected':'reject','observed_lab_parser':'reject','reason':reason})
