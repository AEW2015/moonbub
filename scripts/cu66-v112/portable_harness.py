#!/usr/bin/env python3
"""Recreate V112 fixture locations from retained evidence; keep runner unchanged."""
import argparse
import datetime
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import sys
import tempfile
import zlib

ROOT = Path(__file__).resolve().parents[2]
AREA = ROOT / 'experiments/python-gamebub-v112/portability'
RUNNER = ROOT / 'scripts/cu66-v112/harness/run.py'
SUMMARY = ROOT / 'experiments/python-gamebub-v112/harness/results.json'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def check(condition, message):
    if not condition:
        raise ValueError(message)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check-only', action='store_true',
                        help='Check source bindings and reconstruct fixtures without Docker/build/run.')
    args = parser.parse_args()
    summary = json.loads(SUMMARY.read_text())
    selected = (ROOT / summary['selected_receipt']).resolve()
    selected.relative_to(ROOT)
    check(sha(selected) == summary['selected_sha256'], 'selected receipt hash mismatch')
    receipt = json.loads(selected.read_text())
    check(receipt['status'] == 'PASS_EXPLICIT_SOURCE_ADAPTER_JPEG_RTL', 'selected harness is not PASS')
    for name, expected in receipt['source_sha256'].items():
        check(sha(ROOT / name) == expected, 'current source mismatch: ' + name)
        check(sha(selected.parent / 'sources' / name) == expected, 'source snapshot mismatch: ' + name)
    check(sha(RUNNER) == receipt['source_sha256'][str(RUNNER.relative_to(ROOT))], 'runner is not bound')
    retained = selected.parent / 'guest-accepted-fixture.trace'
    check(sha(retained) == receipt['guest_fixture_trace_sha256'], 'retained fixture trace mismatch')
    check(sha(retained) == receipt['artifact_sha256'][retained.name], 'fixture artifact binding mismatch')

    # Import without writing generated bytecode into the frozen harness directory.
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location('v112_unchanged_harness', RUNNER)
    runner = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(runner)
    base = runner.events(retained)  # Also checks all 28 original V111 event hashes.
    check([hashlib.sha256(e).hexdigest() for e in base] == receipt['original_guest_event_sha256'],
          'original event bindings mismatch')
    expected_length = int.from_bytes(base[0][9:13], 'big')
    expected_crc = int.from_bytes(base[0][13:17], 'big')
    jpeg = bytearray()
    for event in base[1:-1]:
        check(event[0:1] == b'D', 'non-DATA fixture event')
        offset = int.from_bytes(event[9:13], 'big')
        length = int.from_bytes(event[13:15], 'big')
        check(offset == len(jpeg) and 1 <= length <= 1024 and len(event) == length + 15,
              'DATA offset/length mismatch')
        jpeg.extend(event[15:])
    check(len(jpeg) == expected_length, 'reconstructed JPEG length mismatch')
    check(zlib.crc32(jpeg) == expected_crc, 'reconstructed JPEG CRC mismatch')
    check(hashlib.sha256(jpeg).hexdigest() == receipt['jpeg_fixture_sha256'],
          'reconstructed JPEG hash mismatch')

    with tempfile.TemporaryDirectory(prefix='gamebub-v112-portable-fixtures-') as directory:
        prepared = Path(directory)
        shutil.copyfile(retained, prepared / 'fixture.trace')
        (prepared / '0000.jpg').write_bytes(jpeg)
        check(sha(prepared / 'fixture.trace') == receipt['guest_fixture_trace_sha256'], 'prepared trace mismatch')
        check(sha(prepared / '0000.jpg') == receipt['jpeg_fixture_sha256'], 'prepared JPEG mismatch')
        # These are the only imported runner globals changed by this wrapper.
        runner.GUEST = prepared
        runner.JPEG = prepared / '0000.jpg'
        stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
        out = AREA / 'checks' / stamp
        out.mkdir(parents=True)
        result = dict(
            schema='v112-portable-fixture-preparation-v1', status='PASS_FIXTURE_PREPARATION_ONLY',
            selected_harness_receipt=str(selected.relative_to(ROOT)),
            selected_harness_receipt_sha256=sha(selected), selected_summary_sha256=sha(SUMMARY),
            script_sha256=sha(Path(__file__)), runner_sha256=sha(RUNNER),
            retained_trace=str(retained.relative_to(ROOT)), trace_sha256=sha(retained),
            jpeg_sha256=sha(prepared / '0000.jpg'), jpeg_bytes=len(jpeg), jpeg_crc32=f'{expected_crc:08x}',
            original_guest_events=len(base), DATA_events=len(base)-2,
            current_and_snapshot_source_pins_verified=len(receipt['source_sha256']),
            original_guest_event_sha256=receipt['original_guest_event_sha256'],
            temporary_external_fixture_directory=str(prepared), fixtures_deleted_after_return=True,
            overrides=dict(GUEST=str(prepared), JPEG=str(prepared / '0000.jpg')),
            check_only=args.check_only, full_wrapper_harness_run_executed=False,
            original_runner_unchanged=True, DUT_oracle_acceptance_changed=False,
            reconstruction='Concatenate the 26 original hash-verified DATA event payloads in offset order; verify size, CRC32 and original selected JPEG SHA-256.',
            scope='Fixture location portability only; original selected PASS belongs to the unchanged original runner.')
        check_receipt = out / 'receipt.json'
        check_receipt.write_text(json.dumps(result, indent=2, sort_keys=True) + '\n')
        (AREA / 'results.json').write_text(json.dumps(dict(
            schema=result['schema'], status=result['status'],
            selected_check_receipt=str(check_receipt.relative_to(ROOT)),
            selected_check_sha256=sha(check_receipt), full_wrapper_harness_run_executed=False),
            indent=2, sort_keys=True) + '\n')
        print(json.dumps(dict(status=result['status'], DATA_events=26, jpeg_bytes=len(jpeg),
                              jpeg_sha256=result['jpeg_sha256'], source_pins_verified=result['current_and_snapshot_source_pins_verified'],
                              check_receipt=str(check_receipt.relative_to(ROOT)),
                              full_wrapper_harness_run_executed=False), sort_keys=True), flush=True)
        if not args.check_only:
            runner.main()


if __name__ == '__main__':
    main()
